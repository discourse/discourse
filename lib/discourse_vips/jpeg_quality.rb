    def self.estimate(input_path)
      File.open(input_path, "rb") do |file|
        raise ArgumentError, "invalid JPEG header" if file.read(2) != "\xFF\xD8".b

        tables = {}
        lossless = false
        loop do
          raise ArgumentError, "invalid JPEG marker" if file.getbyte != 0xFF

          marker = file.getbyte
          marker = file.getbyte while marker == 0xFF
          raise ArgumentError, "truncated JPEG header" if !marker
          break if marker == 0xDA || marker == 0xD9
          next if marker == 0x01 || (0xD0..0xD7).cover?(marker)

          lossless ||= marker == 0xC3 || marker == 0xCB
          length_bytes = file.read(2)
          raise ArgumentError, "truncated JPEG segment" if length_bytes&.bytesize != 2

          length = length_bytes.unpack1("n") - 2
          if length.negative? || file.pos + length > file.size
            raise ArgumentError, "invalid JPEG segment length"
          end

          if marker == 0xDB
            read_tables(segment: file.read(length), tables:)
          else
            file.seek(length, IO::SEEK_CUR)
          end
        end
        lossless ? 100 : estimate_tables(tables)
      end
    end

    def self.read_tables(segment:, tables:)
      offset = 0
      while offset < segment.bytesize
        definition = segment.getbyte(offset)
        precision = definition >> 4
        identifier = definition & 0x0F
        raise ArgumentError, "invalid JPEG quantization table" if precision > 1 || identifier > 3

        table_bytes = 64 * (precision + 1)
        offset += 1
        values = segment.byteslice(offset, table_bytes)
        raise ArgumentError, "truncated JPEG quantization table" if values&.bytesize != table_bytes

        natural_order = Array.new(64)
        values
          .unpack(precision == 0 ? "C*" : "n*")
          .each_with_index { |value, index| natural_order[ZIGZAG[index]] = value }
        tables[identifier] = natural_order
        offset += table_bytes
      end
    end
    private_class_method :read_tables

    def self.estimate_tables(tables)
      return 92 if !tables[0]

      total = tables.values.sum(&:sum)
      coefficients = tables[0][2] + tables[0][53]
      if tables[1]
        coefficients += tables[1][0] + tables[1][63]
        coefficient_sums = COLOR_COEFFICIENT_SUMS
        table_sums = COLOR_TABLE_SUMS
      else
        coefficient_sums = GRAYSCALE_COEFFICIENT_SUMS
        table_sums = GRAYSCALE_TABLE_SUMS
      end

      100.times do |index|
        next if coefficients < coefficient_sums[index] && total < table_sums[index]

        if (coefficients <= coefficient_sums[index] && total <= table_sums[index]) || index >= 50
          return index + 1
        end
        return 92
      end
      92
    end
    private_class_method :estimate_tables
