  def self.jpeg_quality(path)
    tables = quantization_tables(path)
    luminance = tables[0]
    return 0 if luminance.nil?

    sum = tables.values.flatten.sum
    chrominance = tables[1]

    if chrominance
      qvalue = luminance[2] + luminance[53] + chrominance[0] + chrominance[63]
      estimate(qvalue:, sum:, hash: COLOR_HASH, sums: COLOR_SUMS)
    else
      qvalue = luminance[2] + luminance[53]
      estimate(qvalue:, sum:, hash: GRAYSCALE_HASH, sums: GRAYSCALE_SUMS)
    end
  rescue EOFError, IOError, SystemCallError
    0
  end

  def self.quantization_tables(path)
    File.open(path, "rb") do |file|
      raise EOFError if file.read(2) != "\xFF\xD8".b

      tables = {}
      256.times do
        marker = next_marker(file)
        break if marker == 0xDA || marker == 0xD9
        next if marker == 0x01 || (0xD0..0xD7).cover?(marker)

        length = read_uint16(file)
        raise EOFError if length < 2
        payload = file.read(length - 2)
        raise EOFError if payload.nil? || payload.bytesize != length - 2
        parse_tables(payload:, tables:) if marker == 0xDB
      end
      tables
    end
  end
  private_class_method :quantization_tables

  def self.next_marker(file)
    byte = file.read(1)
    byte = file.read(1) while byte && byte.getbyte(0) != 0xFF
    raise EOFError if byte.nil?

    marker = file.read(1)
    marker = file.read(1) while marker && marker.getbyte(0) == 0xFF
    raise EOFError if marker.nil?
    marker.getbyte(0)
  end
  private_class_method :next_marker

  def self.read_uint16(file)
    bytes = file.read(2)
    raise EOFError if bytes.nil? || bytes.bytesize != 2
    bytes.unpack1("n")
  end
  private_class_method :read_uint16

  def self.parse_tables(payload:, tables:)
    offset = 0
    while offset < payload.bytesize
      descriptor = payload.getbyte(offset)
      offset += 1
      precision = descriptor >> 4
      identifier = descriptor & 0x0F
      bytes_per_value = precision.zero? ? 1 : 2
      byte_length = 64 * bytes_per_value
      raise EOFError if offset + byte_length > payload.bytesize

      values =
        if bytes_per_value == 1
          payload.byteslice(offset, byte_length).unpack("C*")
        else
          payload.byteslice(offset, byte_length).unpack("n*")
        end
      table = Array.new(64)
      values.each_with_index { |value, index| table[ZIGZAG[index]] = value }
      tables[identifier] = table
      offset += byte_length
    end
  end
  private_class_method :parse_tables

  def self.estimate(qvalue:, sum:, hash:, sums:)
    100.times do |index|
      next if qvalue < hash[index] && sum < sums[index]
      return index + 1 if (qvalue <= hash[index] && sum <= sums[index]) || index >= 50
      return 0
    end
    0
  end
  private_class_method :estimate

  private_constant :COLOR_HASH, :COLOR_SUMS, :GRAYSCALE_HASH, :GRAYSCALE_SUMS, :ZIGZAG
